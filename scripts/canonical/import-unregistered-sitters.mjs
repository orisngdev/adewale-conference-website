#!/usr/bin/env node
// The three schools that sat the 2023 zonal finals without ever registering.
//
// From data/canonical/sat-exam-not-registered.csv: Dar-Rahman College, Don Philips
// School and Pakoto High School each sent 3 students to the 2023 exam. The cleanup
// workbook gave them no School ID and left them out of the school tables, so their
// 9 student rows are the only record that they took part.
//
// They are created as schools carrying exclusion_reason and NO school_code, exactly
// like the other deliberately-excluded rows: they stay out of the canonical directory
// and out of any future name matching, while their students' scores are preserved.
// No registration is created, so they never appear in registration reporting — which
// is correct, because they never registered.
//
//   node scripts/canonical/import-unregistered-sitters.mjs --prod

import { createHash, randomUUID } from "node:crypto";
import {
  clean,
  createRestClient,
  loadEnv,
  normalizeSchoolName,
  parseBaseArgs,
  readTable,
  requireCredentials,
  writeReport,
  writeSql,
} from "./lib.mjs";

const EXCLUSION_REASON = "Sat exam, never registered";
const STAGE = "Qualifications";
const STUDENT_EMAIL_DOMAIN = "students.adewaleconference.local";

function hash(input, length = 10) {
  return createHash("sha1").update(input).digest("hex").slice(0, length);
}

async function main() {
  const args = parseBaseArgs(process.argv);
  const envPath = loadEnv(args.envFile);
  console.log(`env       : ${envPath ?? args.envFile}`);
  const { url, key } = requireCredentials();
  console.log(`project   : ${new URL(url).host}`);
  const db = createRestClient(url, key);

  const existing = await db.selectAll("schools", "id,name,school_code,exclusion_reason");
  const byNorm = new Map(existing.map((s) => [normalizeSchoolName(s.name), s]));

  const rows = await readTable(args.sourceDir, "sat-exam-not-registered.csv");
  const schools = new Map();
  const students = [];

  for (const row of rows) {
    const name = clean(row["School (as recorded in results)"]);
    const year = Number(clean(row.Year));
    if (!name || !year) continue;
    const norm = normalizeSchoolName(name);
    if (!schools.has(norm)) {
      schools.set(norm, {
        id: byNorm.get(norm)?.id ?? randomUUID(),
        existing: Boolean(byNorm.get(norm)),
        name,
        lga: clean(row.LGA) || null,
        year,
      });
    }
    const school = schools.get(norm);
    const studentName = clean(row.Student);
    const code = hash(`sitter:${year}:${norm}:${normalizeSchoolName(studentName)}`).toUpperCase();
    students.push({
      id: randomUUID(),
      school_id: school.id,
      name: studentName,
      edition_year: year,
      access_code: code,
      auth_email: `sitter.${code.toLowerCase()}@${STUDENT_EMAIL_DOMAIN}`,
      score: Number(clean(row.Score)) || 0,
      note: `Sat the ${year} zonal finals; school never registered`,
    });
  }

  const toCreate = [...schools.values()].filter((s) => !s.existing);
  console.log("\n── plan ──────────────────────────────────────────────");
  console.log(`schools in the source     : ${schools.size}`);
  console.log(`  already in the database : ${schools.size - toCreate.length}`);
  console.log(`  to create (flagged)     : ${toCreate.length}`);
  for (const s of toCreate) console.log(`      ${s.name} (${s.lga})`);
  console.log(`students to create        : ${students.length}`);
  console.log(`student result rows       : ${students.length}`);

  const reports = [
    await writeReport(
      args.reportDir,
      "unregistered-sitters.csv",
      students.map((s) => ({
        school: [...schools.values()].find((x) => x.id === s.school_id)?.name ?? "",
        student: s.name,
        edition_year: s.edition_year,
        score: s.score,
        access_code: s.access_code,
      })),
    ),
  ];
  console.log(`\nreports:\n${reports.map((r) => `  ${r}`).join("\n")}`);

  const sqlPath = await writeSql(
    args.reportDir,
    "import-unregistered-sitters.sql",
    emitSql([...schools.values()], students),
  );
  console.log(`\nSQL:\n  ${sqlPath}`);
  console.log(`\n  rehearse: psql "$SUPABASE_DB_URL" -f ${sqlPath}`);
  console.log(`  apply   : psql "$SUPABASE_DB_URL" -v apply=true -f ${sqlPath}`);
}

function lit(value) {
  if (value === null || value === undefined || value === "") return "null";
  return `'${String(value).replace(/'/g, "''")}'`;
}

function emitSql(schools, students) {
  const out = [];
  const w = (line = "") => out.push(line);
  w("-- Schools that sat the exam without registering — generated by");
  w("-- scripts/canonical/import-unregistered-sitters.mjs. One transaction, ROLLBACK by default.");
  w("");
  w("\\set ON_ERROR_STOP on");
  w("\\if :{?apply}");
  w("\\else");
  w("  \\set apply false");
  w("\\endif");
  w("");
  w("begin;");
  w("");
  w("-- Flagged, not canonical: no school_code, so they stay out of the directory and");
  w("-- out of future name matching. schools_norm_name_key still guarantees uniqueness.");
  const toCreate = schools.filter((s) => !s.existing);
  if (toCreate.length) {
    w("insert into public.schools (id, name, lga, exclusion_reason) values");
    w(toCreate.map((s) => `  (${lit(s.id)}, ${lit(s.name)}, ${lit(s.lga)}, ${lit(EXCLUSION_REASON)})`).join(",\n"));
    w("on conflict do nothing;");
    w("");
  }
  w("insert into public.students (id, school_id, name, edition_year, access_code, auth_email) values");
  w(students.map((s) => `  (${lit(s.id)}, ${lit(s.school_id)}, ${lit(s.name)}, ${s.edition_year}, ` +
    `${lit(s.access_code)}, ${lit(s.auth_email)})`).join(",\n"));
  w("on conflict (access_code) do nothing;");
  w("");
  w("insert into public.student_stage_results (student_id, stage, edition_year, outcome, score, note)");
  w("select st.id, v.stage, v.edition_year, 'eliminated', v.score, v.note");
  w("from (values");
  w(students.map((s) => `  (${lit(s.access_code)}, ${lit(STAGE)}, ${s.edition_year}, ${s.score}, ${lit(s.note)})`).join(",\n"));
  w(") as v(access_code, stage, edition_year, score, note)");
  w("join public.students st on st.access_code = v.access_code");
  w("on conflict (student_id, stage, edition_year) do update set");
  w("  score = excluded.score, note = excluded.note, updated_at = now();");
  w("");
  w("do $$");
  w("declare n int;");
  w("begin");
  w(`  select count(*) into n from public.schools where exclusion_reason = ${lit(EXCLUSION_REASON)};`);
  w(`  if n <> ${schools.length} then raise exception 'expected ${schools.length} flagged sitter schools, found %', n; end if;`);
  w("  select count(*) into n from public.students st");
  w("    join public.schools s on s.id = st.school_id");
  w(`    where s.exclusion_reason = ${lit(EXCLUSION_REASON)};`);
  w(`  if n <> ${students.length} then raise exception 'expected ${students.length} sitter students, found %', n; end if;`);
  w("  raise notice 'unregistered sitters imported';");
  w("end $$;");
  w("");
  w("select s.name as school, count(st.id) as students, round(avg(r.score),1) as mean_score");
  w("  from public.schools s");
  w("  join public.students st on st.school_id = s.id");
  w("  left join public.student_stage_results r on r.student_id = st.id");
  w(`  where s.exclusion_reason = ${lit(EXCLUSION_REASON)}`);
  w("  group by s.name order by s.name;");
  w("");
  w("\\if :apply");
  w("commit;");
  w("\\echo '>>> COMMITTED'");
  w("\\else");
  w("rollback;");
  w("\\echo '>>> ROLLED BACK — nothing was changed.'");
  w("\\endif");
  return out.join("\n");
}

main().catch((error) => {
  console.error(`\n${error.message}`);
  process.exitCode = 1;
});
