#!/usr/bin/env node
// Remove student result rows duplicated by an unstable match, and nothing else.
//
// import-zonal-results.mjs fetched students without an ORDER BY. Where a school
// registered twice in one year it has two student rows per person, so the candidate
// list had two entries and the code took the first. With no stable order that choice
// differed between runs, so re-running wrote the same score against the other student
// row and left both. The ordering is fixed; this clears up what it already left.
//
// A pair is only treated as duplicated when the two rows carry the SAME score. That
// distinction matters: ITORI COMPREHENSIVE registered twice in 2023 and each of its
// students has one absent sitting (score 0) and one present sitting (a real score),
// with their names reversed between the two entries. Those are two genuine records of
// two sittings, not a double write, and are left alone.
//
//   node scripts/canonical/fix-duplicate-student-results.mjs --prod

import {
  createRestClient,
  loadEnv,
  normalizeSchoolName,
  parseBaseArgs,
  requireCredentials,
  writeReport,
  writeSql,
} from "./lib.mjs";

function nameTokens(value) {
  return normalizeSchoolName(value).split(" ").filter((t) => t.length > 1).sort().join(" ");
}

async function main() {
  const args = parseBaseArgs(process.argv);
  const envPath = loadEnv(args.envFile);
  console.log(`env       : ${envPath ?? args.envFile}`);
  const { url, key } = requireCredentials();
  console.log(`project   : ${new URL(url).host}`);
  const db = createRestClient(url, key);

  const [students, results, schools] = await Promise.all([
    db.selectAll("students", "id,school_id,name,edition_year,created_at", { order: "created_at,id" }),
    db.selectAll("student_stage_results", "id,student_id,stage,edition_year,score,created_at", {
      order: "created_at,id",
    }),
    db.selectAll("schools", "id,name"),
  ]);
  const studentById = new Map(students.map((s) => [s.id, s]));
  const schoolName = new Map(schools.map((s) => [s.id, s.name]));

  const groups = new Map();
  for (const row of results) {
    const student = studentById.get(row.student_id);
    if (!student) continue;
    const key = [student.school_id, row.edition_year, row.stage, nameTokens(student.name)].join("|");
    if (!groups.has(key)) groups.set(key, []);
    groups.get(key).push({ row, student });
  }

  const remove = [];
  const kept = [];
  for (const entries of groups.values()) {
    if (entries.length < 2) continue;
    // Same score => the same source row written twice. Different scores => different
    // sittings, which a school that registered twice genuinely has.
    const byScore = new Map();
    for (const e of entries) {
      const score = e.row.score === null ? "null" : String(e.row.score);
      if (!byScore.has(score)) byScore.set(score, []);
      byScore.get(score).push(e);
    }
    for (const [score, sameScore] of byScore) {
      if (sameScore.length < 2) {
        kept.push({ reason: "distinct score — separate sitting", score, ...describe(sameScore[0], schoolName) });
        continue;
      }
      // Keep the row on the student created first; that is now what the fixed
      // matcher would pick, so a future re-run is a no-op.
      const ordered = [...sameScore].sort(
        (a, b) =>
          String(a.student.created_at).localeCompare(String(b.student.created_at)) ||
          a.student.id.localeCompare(b.student.id),
      );
      kept.push({ reason: "kept", score, ...describe(ordered[0], schoolName) });
      for (const surplus of ordered.slice(1)) {
        remove.push({ result_id: surplus.row.id, score, ...describe(surplus, schoolName) });
      }
    }
  }

  console.log("\n── plan ──────────────────────────────────────────────");
  console.log(`student result rows        : ${results.length}`);
  console.log(`surplus rows to remove     : ${remove.length}`);
  console.log(`legitimate second sittings : ${kept.filter((k) => k.reason !== "kept").length}`);
  for (const r of remove) {
    console.log(`  ${r.edition_year}  ${r.school.slice(0, 40).padEnd(42)} ${r.student.slice(0, 26).padEnd(28)} score=${r.score}`);
  }

  const reports = [
    await writeReport(args.reportDir, "duplicate-student-results-removed.csv", remove),
    await writeReport(args.reportDir, "duplicate-student-results-kept.csv", kept),
  ];
  console.log(`\nreports:\n${reports.map((r) => `  ${r}`).join("\n")}`);

  const out = [];
  const w = (line = "") => out.push(line);
  w("-- Remove student result rows duplicated by an unstable match.");
  w("-- Generated by scripts/canonical/fix-duplicate-student-results.mjs.");
  w("");
  w("\\set ON_ERROR_STOP on");
  w("\\if :{?apply}");
  w("\\else");
  w("  \\set apply false");
  w("\\endif");
  w("");
  w("begin;");
  w("");
  if (remove.length) {
    w(`delete from public.student_stage_results where id in (`);
    w(remove.map((r) => `  '${r.result_id}'`).join(",\n"));
    w(");");
    w("");
  }
  w("do $$");
  w("declare n int;");
  w("begin");
  w("  select count(*) into n from public.student_stage_results;");
  w(`  if n <> ${results.length - remove.length} then`);
  w(`    raise exception 'student_stage_results is %, expected ${results.length - remove.length}', n;`);
  w("  end if;");
  w("  raise notice 'removed % duplicated result rows', " + remove.length + ";");
  w("end $$;");
  w("");
  w("select r.edition_year, count(*) as rows, round(avg(r.score),1) as mean, max(r.score) as best");
  w("  from public.student_stage_results r");
  w("  join public.students st on st.id = r.student_id");
  w("  join public.schools s on s.id = st.school_id");
  w("  where s.exclusion_reason is distinct from 'Sat exam, never registered'");
  w("  group by 1 order by 1;");
  w("");
  w("\\if :apply");
  w("commit;");
  w("\\echo '>>> COMMITTED'");
  w("\\else");
  w("rollback;");
  w("\\echo '>>> ROLLED BACK — nothing was changed.'");
  w("\\endif");

  const sqlPath = await writeSql(args.reportDir, "fix-duplicate-student-results.sql", out.join("\n"));
  console.log(`\nSQL:\n  ${sqlPath}`);
  console.log(`\n  rehearse: psql "$SUPABASE_DB_URL" -f ${sqlPath}`);
  console.log(`  apply   : psql "$SUPABASE_DB_URL" -v apply=true -f ${sqlPath}`);
}

function describe(entry, schoolName) {
  return {
    edition_year: entry.row.edition_year,
    school: schoolName.get(entry.student.school_id) ?? "",
    student: entry.student.name,
    student_id: entry.student.id,
  };
}

main().catch((error) => {
  console.error(`\n${error.message}`);
  process.exitCode = 1;
});
